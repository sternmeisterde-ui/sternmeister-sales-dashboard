-- 0037_sla_first_call_manager.sql
--
-- «Своё» SLA Госников (Бух Гос) считается по спеке РОПа так же, как у Комм, но
-- с другой привязкой: в Kommo ответственным за свежий лид стоит РОП (296 из 302
-- «Потерянных» на нём), поэтому по ответственному разрез бессмыслен. Привязка —
-- к тому, КТО СДЕЛАЛ ПЕРВОЕ КАСАНИЕ: автор первого исходящего звонка по лиду из
-- телефонии. Его имя и кладём сюда на этапе compute-sla, чтобы разбивка «SLA по
-- менеджерам» не пересобирала communications на каждое чтение.
--
-- NULL = звонка ещё не было (лид открыт и ждёт) либо лид не b2g.
-- Для Комм колонка не используется: там SLA привязан к ответственному (sla.manager).
--
-- Apply via Neon SQL editor (Analytics DB).

ALTER TABLE analytics.sla
  ADD COLUMN IF NOT EXISTS first_call_manager text;

COMMENT ON COLUMN analytics.sla.first_call_manager IS
  'Автор ПЕРВОГО исходящего звонка по лиду (analytics.communications.manager). Кому засчитывается «своё» SLA Госников — в Kommo ответственным за свежий лид стоит РОП, поэтому по нему считать нельзя. NULL = звонка не было.';
