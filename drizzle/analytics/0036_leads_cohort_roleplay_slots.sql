-- 0036_leads_cohort_roleplay_slots.sql
-- Слепок «ролевочных» полей карточки сделки Kommo — то, что менеджер выставил
-- РУКАМИ. Нужен, чтобы таблица «Ролевки» показывала расхождение «оценил бот ↔
-- стоит в Kommo» (авто-запись write-back в ОКК живёт под KOMMO_WRITE_ENABLED и
-- по умолчанию dry-run, поэтому сегодня в полях ручные оценки).
--
-- Поля Kommo (подтверждены GET /leads/custom_fields 2026-07-28, 3 слота на
-- сторону; enum-значения select-полей — литералы «1».. «5»):
--   ДЦ: 891978/891980 (дата/оценка-1), 891982/891984 (-2), 891986/891988 (-3)
--   АА: 891990/891992 (дата/оценка-1), 891994/891996 (-2), 891998/892000 (-3)
--
-- Почему JSONB, а не 12 колонок или отдельная таблица: sync-leads пишет
-- leads_cohort через DELETE+INSERT одной строкой на сделку — один JSONB едет
-- этим же путём и остаётся идемпотентным (docs/etl-architecture.md). Отдельная
-- таблица потребовала бы своего delete-then-insert с ретрай-опасностью, а
-- фильтруем мы по дате термина, не по слотам, так что индекс не нужен.
--
-- Формат: [{"side":"dc","attempt":1,"score":4,"date":"2026-07-14"}, ...]
-- Только ЗАПОЛНЕННЫЕ слоты (пустое поле в Kommo = слота нет).
--
-- ⚠ NULL ≠ пустой массив:
--   NULL — сделку не синкали после этой миграции, данных из Kommo НЕТ;
--   []   — синкали, ни одного слота не заполнено.
-- Таблица «Ролевки» на NULL показывает «н/д» и НЕ считает расхождение —
-- иначе до бэкфилла (scripts/backfill-roleplay-slots.ts) вся таблица была бы
-- красной.

ALTER TABLE analytics.leads_cohort
  ADD COLUMN IF NOT EXISTS roleplay_slots JSONB;

COMMENT ON COLUMN analytics.leads_cohort.roleplay_slots IS
  'Ручные оценки ролевок из карточки Kommo: [{side,attempt,score,date}]. Заполняется sync-leads из CF 891978..892000. NULL = не синкалось после миграции 0036.';
